export type TranslationNamespace = keyof typeof translations.en;
export type TranslationKey<N extends TranslationNamespace> = keyof (typeof translations.en)[N];

export function interpolateTranslation(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{\{?(\w+)\}\}?/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

export const languageOptions: {
  key: AppLanguage;
  label: string;
  description: string;
  emoji: string;
}[] = [
  { key: 'system', label: 'Follow system', description: 'Use your device language', emoji: '📱' },
  { key: 'en', label: 'English', description: 'English interface', emoji: '🇬🇧' },
  { key: 'zh', label: '中文', description: '简体中文界面', emoji: '🇨🇳' },
];

export function getSystemLanguage(): ResolvedLanguage {
  const locale = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
  return locale.startsWith('zh') ? 'zh' : 'en';
}

export function resolveLanguage(preference?: string | null): ResolvedLanguage {
  if (preference === 'zh') return 'zh';
  if (preference === 'en') return 'en';
  return getSystemLanguage();
}

export function getLanguageLabel(language: AppLanguage): string {
  if (language === 'system')
    return `Follow system · ${resolveLanguage(language) === 'zh' ? '中文' : 'English'}`;
  return language === 'zh' ? '中文' : 'English';
}
